package com.example.api_cd_produto.model;

public class DadosFirma {
    private String livro;
    private String folha;
    private String dataReconhecimentoFirma;

    // Getters e Setters
    public String getLivro() { return livro; }
    public void setLivro(String livro) { this.livro = livro; }
    public String getFolha() { return folha; }
    public void setFolha(String folha) { this.folha = folha; }
    public String getDataReconhecimentoFirma() { return dataReconhecimentoFirma; }
    public void setDataReconhecimentoFirma(String dataReconhecimentoFirma) { this.dataReconhecimentoFirma = dataReconhecimentoFirma; }
}
